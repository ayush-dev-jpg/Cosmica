# KNOWLEDGE BASE SYSTEM
# Admin uploads PDF books → extracted → embedded → stored in ChromaDB
# Later used for AI-powered predictions via RAG
# =====================================================

import chromadb
from chromadb.utils import embedding_functions
import PyPDF2
import uuid
import io
from app.core.config import settings

# ---------------------------------------------------
# Initialize ChromaDB (persistent vector database)
# ---------------------------------------------------
chroma_client = chromadb.PersistentClient(path=settings.CHROMA_DB_PATH)

# Use sentence-transformers for local embeddings (no API cost)
embedding_fn = embedding_functions.SentenceTransformerEmbeddingFunction(
    model_name="all-MiniLM-L6-v2"
)

# Get or create the astrology knowledge collection
knowledge_collection = chroma_client.get_or_create_collection(
    name="astrology_knowledge",
    embedding_function=embedding_fn
)

# ---------------------------------------------------
# TEXT EXTRACTION
# ---------------------------------------------------

def extract_text_from_pdf(file_bytes: bytes) -> str:
    """Extract all text from a PDF file"""
    try:
        reader = PyPDF2.PdfReader(io.BytesIO(file_bytes))
        text = ""
        for page_num, page in enumerate(reader.pages):
            page_text = page.extract_text()
            if page_text:
                text += f"\n[Page {page_num + 1}]\n{page_text}\n"
        return text
    except Exception as e:
        raise ValueError(f"Failed to read PDF: {str(e)}")

def extract_text_from_txt(file_bytes: bytes) -> str:
    """Extract text from a plain text file"""
    return file_bytes.decode("utf-8", errors="ignore")

# ---------------------------------------------------
# TEXT CHUNKING
# ---------------------------------------------------

def chunk_text(text: str, chunk_size: int = 400, overlap: int = 50) -> list[str]:
    """
    Split text into overlapping chunks for better retrieval.
    Overlap ensures context isn't lost at chunk boundaries.
    """
    words = text.split()
    chunks = []

    for i in range(0, len(words), chunk_size - overlap):
        chunk_words = words[i:i + chunk_size]
        if len(chunk_words) > 20:   # Skip very tiny chunks
            chunks.append(" ".join(chunk_words))

    return chunks

# ---------------------------------------------------
# INGESTION PIPELINE
# ---------------------------------------------------

def ingest_document(text: str, source_name: str, category: str = "general") -> dict:
    """
    Full pipeline: text → chunks → embeddings → ChromaDB storage

    Args:
        text: The full text content
        source_name: Name/filename of the source
        category: Category tag (e.g. "nakshatra", "remedies", "general")
    """
    # Split into chunks
    chunks = chunk_text(text)

    if not chunks:
        return {"status": "error", "message": "No text content found"}

    # Create unique IDs for each chunk
    ids = [f"{source_name.replace(' ', '_')}_{i}_{uuid.uuid4().hex[:6]}"
           for i in range(len(chunks))]

    # Metadata for each chunk (for filtering later)
    metadatas = [
        {
            "source": source_name,
            "category": category,
            "chunk_index": i,
            "total_chunks": len(chunks)
        }
        for i in range(len(chunks))
    ]

    # Store in ChromaDB (embeddings are auto-generated by the embedding_fn)
    knowledge_collection.add(
        documents=chunks,
        metadatas=metadatas,
        ids=ids
    )

    return {
        "status": "success",
        "source": source_name,
        "category": category,
        "chunks_stored": len(chunks),
        "total_characters": len(text),
    }

# ---------------------------------------------------
# SEARCH
# ---------------------------------------------------

def search_knowledge(query: str, top_k: int = 5, category: str = None) -> list[str]:
    """
    Semantic search across all ingested knowledge.
    Returns most relevant text passages for a query.
    """
    try:
        # Optional: filter by category
        where_filter = {"category": category} if category else None

        results = knowledge_collection.query(
            query_texts=[query],
            n_results=min(top_k, knowledge_collection.count() or 1),
            where=where_filter
        )

        # Return just the text passages
        if results and results["documents"]:
            return results["documents"][0]
        return []

    except Exception as e:
        print(f"Search error: {e}")
        return []

def list_sources() -> list[dict]:
    """List all ingested knowledge sources"""
    try:
        all_data = knowledge_collection.get(include=["metadatas"])
        sources = {}
        for meta in all_data.get("metadatas", []):
            source = meta.get("source", "Unknown")
            if source not in sources:
                sources[source] = {
                    "name": source,
                    "category": meta.get("category", "general"),
                    "chunks": 0
                }
            sources[source]["chunks"] += 1
        return list(sources.values())
    except Exception:
        return []

def delete_source(source_name: str) -> dict:
    """Delete all chunks from a specific source"""
    try:
        all_data = knowledge_collection.get(include=["metadatas"])
        ids_to_delete = [
            all_data["ids"][i]
            for i, meta in enumerate(all_data.get("metadatas", []))
            if meta.get("source") == source_name
        ]
        if ids_to_delete:
            knowledge_collection.delete(ids=ids_to_delete)
        return {"deleted": len(ids_to_delete), "source": source_name}
    except Exception as e:
        return {"error": str(e)}
